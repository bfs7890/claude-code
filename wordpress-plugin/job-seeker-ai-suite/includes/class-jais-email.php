<?php
if ( ! defined( 'ABSPATH' ) ) exit;

class JAIS_Email {

	public function __construct() {
		add_action( 'wp_ajax_jais_send_results',        [ $this, 'ajax_handler' ] );
		add_action( 'wp_ajax_nopriv_jais_send_results', [ $this, 'ajax_handler' ] );
	}

	public function ajax_handler(): void {
		check_ajax_referer( 'jais_nonce', 'nonce' );

		if ( ! get_option( 'jais_email_enabled', '1' ) ) {
			wp_send_json_error( 'Email notifications are disabled.' );
		}

		$user_email  = sanitize_email( wp_unslash( $_POST['user_email'] ?? '' ) );
		$module      = sanitize_key( wp_unslash( $_POST['module']      ?? '' ) );
		$result_text = sanitize_textarea_field( wp_unslash( $_POST['result_text'] ?? '' ) );

		if ( ! is_email( $user_email ) ) {
			wp_send_json_error( 'Please enter a valid email address.' );
		}

		if ( empty( $result_text ) ) {
			wp_send_json_error( 'No result to send.' );
		}

		$module_labels = [
			'cv_tailor'      => 'CV Tailor',
			'skills_gap'     => 'Skills Gap Analyser',
			'job_decoder'    => 'Job Decoder',
			'company_brief'  => 'Company Briefing',
			'interview_prep' => 'Interview Prep Coach',
			'negotiation'    => 'Salary Negotiation Coach',
			'prioritiser'    => 'Smart Job Prioritiser',
			'burnout'        => 'Wellbeing & Burnout Tracker',
			'video_sim'      => 'Video Interview Simulator',
		];

		$module_label = $module_labels[ $module ] ?? ucwords( str_replace( '_', ' ', $module ) );
		$site_name    = get_bloginfo( 'name' );
		$admin_email  = get_option( 'jais_admin_notify_email', get_option( 'admin_email' ) );

		// ── Email to user ────────────────────────────────────
		$user_subject = "[{$site_name}] Your {$module_label} Results";
		$user_body    = $this->build_user_email( $module_label, $result_text, $site_name );

		wp_mail(
			$user_email,
			$user_subject,
			$user_body,
			[ 'Content-Type: text/html; charset=UTF-8' ]
		);

		// ── Notification to admin ────────────────────────────
		if ( get_option( 'jais_admin_notify_enabled', '1' ) && is_email( $admin_email ) ) {
			$admin_subject = "[{$site_name}] Job Seeker AI — {$module_label} used";
			$admin_body    = $this->build_admin_email( $module_label, $user_email, $result_text, $site_name );

			wp_mail(
				$admin_email,
				$admin_subject,
				$admin_body,
				[ 'Content-Type: text/html; charset=UTF-8' ]
			);
		}

		wp_send_json_success( 'Results sent to ' . $user_email );
	}

	private function build_user_email( string $module_label, string $result_text, string $site_name ): string {
		$result_html = nl2br( esc_html( $result_text ) );
		return "
<!DOCTYPE html>
<html>
<head><meta charset='UTF-8'></head>
<body style='font-family:Arial,sans-serif;max-width:600px;margin:0 auto;padding:20px;color:#333'>
  <div style='background:#1B6CA8;padding:20px;border-radius:8px 8px 0 0'>
    <h1 style='color:#fff;margin:0;font-size:22px'>{$site_name}</h1>
    <p style='color:#cde;margin:4px 0 0'>Job Seeker AI Suite</p>
  </div>
  <div style='background:#f9f9f9;padding:24px;border:1px solid #e0e0e0'>
    <h2 style='color:#1B6CA8;margin-top:0'>Your {$module_label} Results</h2>
    <div style='background:#fff;padding:16px;border-radius:6px;border:1px solid #e8e8e8;font-size:14px;line-height:1.7'>
      {$result_html}
    </div>
    <p style='margin-top:20px;font-size:13px;color:#777'>
      These results were generated by AI and are for guidance only. Always verify information independently.
    </p>
  </div>
  <div style='padding:16px;text-align:center;font-size:12px;color:#999'>
    Sent by {$site_name} · Job Seeker AI Suite
  </div>
</body>
</html>";
	}

	private function build_admin_email( string $module_label, string $user_email, string $result_text, string $site_name ): string {
		$result_html = nl2br( esc_html( $result_text ) );
		$time        = current_time( 'mysql' );
		return "
<!DOCTYPE html>
<html>
<head><meta charset='UTF-8'></head>
<body style='font-family:Arial,sans-serif;max-width:600px;margin:0 auto;padding:20px;color:#333'>
  <div style='background:#333;padding:20px;border-radius:8px 8px 0 0'>
    <h1 style='color:#fff;margin:0;font-size:18px'>Job Seeker AI — Activity Notification</h1>
  </div>
  <div style='background:#f9f9f9;padding:24px;border:1px solid #e0e0e0'>
    <table style='width:100%;font-size:14px'>
      <tr><td style='color:#777;width:120px'>Module:</td><td><strong>{$module_label}</strong></td></tr>
      <tr><td style='color:#777'>User email:</td><td><strong>{$user_email}</strong></td></tr>
      <tr><td style='color:#777'>Time:</td><td>{$time}</td></tr>
      <tr><td style='color:#777'>Site:</td><td>{$site_name}</td></tr>
    </table>
    <h3 style='color:#1B6CA8;margin-top:20px'>Result Summary</h3>
    <div style='background:#fff;padding:16px;border-radius:6px;border:1px solid #e8e8e8;font-size:13px;line-height:1.6'>
      {$result_html}
    </div>
  </div>
</body>
</html>";
	}
}
